/* Edge cases that could cause the proposed UI to make an invalid recommendation. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {improvementStats,validateImprovementCase,improvementDecision}=require('./dist/task-improvement.js');
const model=JSON.parse(fs.readFileSync(__dirname+'/content/task-improvement.json','utf8'));
for(const c of model.cases)assert.equal(validateImprovementCase(c,model.stages),true);
const c=id=>model.cases.find(c=>c.id===id);
const zero=c('zero_task');
assert.equal(zero.fullTaskSuccess,0);
assert.ok(zero.rows.some(r=>r.passed>0));
assert.equal(improvementDecision(zero,'clear').kind,'correction','Zero task success must not erase local progress');
assert.equal(improvementStats(zero.rows.at(-1)).rate,null,'Never-reached stage cannot be 0% failure');
assert.equal(zero.rows.at(-1).failed,0);
const unknown=improvementStats(c('unknown').rows[1]);
assert.equal(unknown.rate,null);
assert.equal(unknown.coverage,0);
assert.equal(unknown.lower,0);
assert.equal(unknown.upper,1);
assert.equal(improvementDecision(c('unknown'),'clear').kind,'observe');
for(const example of model.cases)assert.equal(improvementDecision(example,'repair').kind,'repair','Confirmed binding error precedes data intervention');
assert.equal(improvementDecision(c('bootstrap'),'clear').kind,'bootstrap');
const partial=improvementStats({entered:100,passed:50,failed:10,unknown:40,notAttempted:0});
assert.equal(partial.coverage,.6);
assert.equal(partial.rate,50/60);
assert.equal(partial.lower,.5);assert.equal(partial.upper,.9);
assert.throws(()=>improvementStats({entered:10,passed:8,failed:5,unknown:0,notAttempted:90}),/account/);
assert.throws(()=>improvementStats({entered:10,passed:-1,failed:11,unknown:0,notAttempted:90}),/Invalid/);
const bad=structuredClone(zero);bad.rows[4]={stageId:'release',entered:1,passed:1,failed:0,unknown:0,notAttempted:99};
assert.throws(()=>validateImprovementCase(bad,model.stages),/cannot be reached/);
const badSuccess=structuredClone(zero);badSuccess.fullTaskSuccess=1;
assert.throws(()=>validateImprovementCase(badSuccess,model.stages),/exceeds/);
const costCode=fs.readFileSync(__dirname+'/dist/cost-model.js','utf8');
const context=vm.createContext({});vm.runInContext(costCode,context);
const inputs=JSON.parse(fs.readFileSync(__dirname+'/content/industrial-cost-model.json','utf8'));
const defaults=context.costDefaults(inputs),base=context.calculateIndustrialCost(defaults);
assert.ok(Math.abs(base.baseline-9315.89)<.02,'Original snapshot preserved, additional quantities remain unknown');
const probe=context.calculateIndustrialCost({...defaults,candidateProbeRobotHours:2});
assert.ok(Math.abs(probe.candidate-base.candidate-2*(base.op+base.robotHour))<1e-8,'Probe reset accounts operator and robot exactly once');
assert.ok(Math.abs(probe.candidateYearCash-base.candidateYearCash-2*(base.op+base.robotHour-base.capitalHour)*defaults.reuseSkills)<1e-8,'Cash excludes allocated capital already purchased');
const boot=context.calculateIndustrialCost({...defaults,sharedBootstrapHours:5});
assert.ok(Math.abs(boot.saving-base.saving)<1e-8,'Shared bootstrap cannot create fake arm advantage');
assert.ok(Math.abs(boot.baseline-base.baseline-5*base.eng)<1e-8);
console.log('Passed improvement accounting, unknown/never-reached, repair/cold-start gates and non-duplicated cost checks.');
